drop policy if exists customer_report_proofs_insert_own on storage.objects;
create policy customer_report_proofs_insert_own on storage.objects
for insert to authenticated
with check (
    bucket_id = 'customer-report-proofs'
    and (storage.foldername(name))[1] = auth.uid()::text
    and exists (
        select 1
        from public.users u
        join public.customers c on c.user_id = u.id
        where u.auth_user_id = auth.uid()
    )
);

