-- Customer cancellation requests with caterer-reviewed, manually recorded refunds.
-- Run after supabase_reservation_end_time_migration.sql and
-- supabase_gcash_manual_payments_migration.sql.

create table if not exists public.reservation_cancellation_requests (
    id bigint generated by default as identity primary key,
    reservation_id bigint not null references public.reservations(id) on delete cascade,
    customer_id bigint not null references public.customers(id) on delete cascade,
    request_status varchar(20) not null default 'pending'
        check (request_status in ('pending', 'approved', 'rejected')),
    reason text not null,
    requested_at timestamptz not null default now(),
    reviewed_at timestamptz,
    review_note text,
    refund_amount numeric(10,2) not null default 0 check (refund_amount >= 0),
    refund_status varchar(20) not null default 'not_required'
        check (refund_status in ('not_required', 'pending', 'refunded')),
    refund_reference text,
    refunded_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create unique index if not exists reservation_cancellation_one_pending_per_booking
    on public.reservation_cancellation_requests (reservation_id)
    where request_status = 'pending';

create index if not exists reservation_cancellation_requests_customer_latest
    on public.reservation_cancellation_requests (customer_id, reservation_id, id desc);

create index if not exists reservation_cancellation_requests_status
    on public.reservation_cancellation_requests (request_status, refund_status);

alter table public.reservation_cancellation_requests enable row level security;

create or replace function public.request_reservation_cancellation(
    p_reservation_id bigint,
    p_reason text
)
returns bigint
language plpgsql
security definer set search_path = public
as $$
declare
    customer_profile_id bigint;
    request_id bigint;
begin
    select customer_id into customer_profile_id
    from public.get_my_profile()
    where role = 'customer';

    if customer_profile_id is null then
        raise exception 'Customer access required.';
    end if;

    if length(trim(coalesce(p_reason, ''))) < 5 or length(trim(p_reason)) > 1000 then
        raise exception 'Enter a cancellation reason between 5 and 1000 characters.';
    end if;

    if not exists (
        select 1
        from public.reservations r
        where r.id = p_reservation_id
          and r.customer_id = customer_profile_id
          and r.reservation_status in ('pending', 'confirmed')
    ) then
        raise exception 'Only active bookings can be submitted for cancellation.';
    end if;

    insert into public.reservation_cancellation_requests (
        reservation_id, customer_id, reason
    )
    values (
        p_reservation_id, customer_profile_id, trim(p_reason)
    )
    returning id into request_id;

    return request_id;
exception
    when unique_violation then
        raise exception 'A cancellation request is already waiting for review.';
end;
$$;

create or replace function public.get_my_cancellation_requests()
returns table (
    reservation_id bigint,
    request_id bigint,
    request_status varchar,
    request_reason text,
    request_requested_at timestamptz,
    request_review_note text,
    payment_method varchar,
    refund_amount numeric,
    refund_status varchar,
    refund_reference text,
    refunded_at timestamptz
)
language sql
stable
security definer set search_path = public
as $$
    select distinct on (request.reservation_id)
        request.reservation_id,
        request.id,
        request.request_status,
        request.reason,
        request.requested_at,
        request.review_note,
        coalesce(
            reservation.booking_payment_method,
            (
                select payment.payment_method
                from public.payments payment
                where payment.reservation_id = reservation.id
                  and payment.payment_status = 'completed'
                order by payment.created_at
                limit 1
            )
        ),
        request.refund_amount,
        request.refund_status,
        request.refund_reference,
        request.refunded_at
    from public.reservation_cancellation_requests request
    join public.reservations reservation on reservation.id = request.reservation_id
    where request.customer_id = (
        select customer_id
        from public.get_my_profile()
        where role = 'customer'
    )
    order by request.reservation_id, request.id desc;
$$;

create or replace function public.get_caterer_cancellation_requests()
returns table (
    request_id bigint,
    reservation_id bigint,
    customer_name varchar,
    package_name varchar,
    event_date date,
    payment_method varchar,
    paid_amount numeric,
    request_reason text,
    request_requested_at timestamptz,
    request_status varchar,
    review_note text,
    refund_amount numeric,
    refund_status varchar,
    refund_reference text
)
language sql
stable
security definer set search_path = public
as $$
    select
        request.id,
        reservation.id,
        customer.full_name,
        package.package_name,
        reservation.event_date,
        coalesce(
            reservation.booking_payment_method,
            (
                select payment.payment_method
                from public.payments payment
                where payment.reservation_id = reservation.id
                  and payment.payment_status = 'completed'
                order by payment.created_at
                limit 1
            )
        ),
        coalesce((
            select sum(payment.amount)
            from public.payments payment
            where payment.reservation_id = reservation.id
              and payment.payment_status = 'completed'
        ), 0),
        request.reason,
        request.requested_at,
        request.request_status,
        request.review_note,
        request.refund_amount,
        request.refund_status,
        request.refund_reference
    from public.reservation_cancellation_requests request
    join public.reservations reservation on reservation.id = request.reservation_id
    join public.customers customer on customer.id = request.customer_id
    join public.packages package on package.id = reservation.package_id
    where reservation.caterer_id = (
        select caterer_id
        from public.get_my_profile()
        where role = 'caterer'
    )
      and request.request_status in ('pending', 'approved')
    order by request.requested_at asc;
$$;

create or replace function public.review_reservation_cancellation(
    p_request_id bigint,
    p_approve boolean,
    p_review_note text,
    p_refund_amount numeric
)
returns void
language plpgsql
security definer set search_path = public
as $$
declare
    request_row public.reservation_cancellation_requests%rowtype;
    paid_total numeric(10,2);
begin
    select request.*
    into request_row
    from public.reservation_cancellation_requests request
    join public.reservations reservation on reservation.id = request.reservation_id
    where request.id = p_request_id
      and request.request_status = 'pending'
      and reservation.caterer_id = (
          select caterer_id
          from public.get_my_profile()
          where role = 'caterer'
      )
    for update of request;

    if not found then
        raise exception 'This cancellation request is no longer waiting for review.';
    end if;

    if p_approve then
        select coalesce(sum(payment.amount), 0)
        into paid_total
        from public.payments payment
        where payment.reservation_id = request_row.reservation_id
          and payment.payment_status = 'completed';

        if p_refund_amount is null
           or p_refund_amount < 0
           or p_refund_amount > paid_total
           or round(p_refund_amount, 2) <> p_refund_amount then
            raise exception 'Refund amount must be between zero and the total amount received (%).', paid_total;
        end if;
        if paid_total > 0
           and p_refund_amount < paid_total
           and length(trim(coalesce(p_review_note, ''))) < 5 then
            raise exception 'Explain why the refund is less than the amount received (at least 5 characters).';
        end if;

        update public.reservation_cancellation_requests
        set request_status = 'approved',
            reviewed_at = now(),
            review_note = nullif(trim(coalesce(p_review_note, '')), ''),
            refund_amount = p_refund_amount,
            refund_status = case when p_refund_amount > 0 then 'pending' else 'not_required' end,
            updated_at = now()
        where id = request_row.id;

        update public.reservations
        set reservation_status = 'cancelled',
            updated_at = now()
        where id = request_row.reservation_id
          and reservation_status in ('pending', 'confirmed');

        if not found then
            raise exception 'The booking is no longer active.';
        end if;

        update public.payments
        set payment_status = 'failed',
            review_note = 'Booking cancelled; unconfirmed payment was not included in the refund.',
            updated_at = now()
        where reservation_id = request_row.reservation_id
          and payment_status = 'pending';
    else
        if length(trim(coalesce(p_review_note, ''))) < 5
           or length(trim(p_review_note)) > 500 then
            raise exception 'Enter a reason for declining the request between 5 and 500 characters.';
        end if;

        update public.reservation_cancellation_requests
        set request_status = 'rejected',
            reviewed_at = now(),
            review_note = trim(p_review_note),
            updated_at = now()
        where id = request_row.id;
    end if;
end;
$$;

create or replace function public.record_reservation_refund(
    p_request_id bigint,
    p_refund_reference text
)
returns void
language plpgsql
security definer set search_path = public
as $$
begin
    if length(trim(coalesce(p_refund_reference, ''))) < 3
       or length(trim(p_refund_reference)) > 200 then
        raise exception 'Enter the PayPal transaction ID or GCash reference number (3 to 200 characters).';
    end if;

    update public.reservation_cancellation_requests request
    set refund_status = 'refunded',
        refund_reference = trim(p_refund_reference),
        refunded_at = now(),
        updated_at = now()
    from public.reservations reservation
    where request.id = p_request_id
      and request.reservation_id = reservation.id
      and request.request_status = 'approved'
      and request.refund_status = 'pending'
      and reservation.caterer_id = (
          select caterer_id
          from public.get_my_profile()
          where role = 'caterer'
      );

    if not found then
        raise exception 'Only an approved refund awaiting transfer can be recorded.';
    end if;
end;
$$;

