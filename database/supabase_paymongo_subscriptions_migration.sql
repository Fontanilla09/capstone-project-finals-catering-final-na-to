-- PayMongo QR Ph subscriptions.
-- Run after supabase_auth_migration.sql, supabase_caterer_suspension_migration.sql,
-- supabase_package_management_migration.sql, and supabase_ai_generated_images_migration.sql.

create table if not exists public.caterer_subscriptions (
    id bigint generated by default as identity primary key,
    caterer_id bigint not null references public.caterers(id) on delete cascade,
    plan text not null check (plan in ('monthly', 'yearly')),
    amount integer not null check (amount in (49900, 479000)),
    currency text not null default 'PHP' check (currency = 'PHP'),
    status text not null default 'pending' check (status in ('pending', 'active', 'expired', 'failed')),
    paymongo_checkout_session_id text not null unique,
    paymongo_payment_id text unique,
    reference_number text not null unique,
    started_at timestamptz,
    expires_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index if not exists idx_caterer_subscriptions_latest
    on public.caterer_subscriptions (caterer_id, created_at desc);

alter table public.caterer_subscriptions enable row level security;
revoke all on public.caterer_subscriptions from public, anon, authenticated;
grant all on public.caterer_subscriptions to service_role;
grant usage, select on sequence public.caterer_subscriptions_id_seq to service_role;

create or replace function public.caterer_has_active_subscription(p_caterer_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select exists (
        select 1
        from public.caterer_subscriptions s
        join public.caterers c on c.id = s.caterer_id
        where s.caterer_id = p_caterer_id
          and c.is_suspended = false
          and s.status = 'active'
          and s.expires_at > now()
    );
$$;

revoke all on function public.caterer_has_active_subscription(bigint) from public, anon, authenticated;
grant execute on function public.caterer_has_active_subscription(bigint) to service_role;

create or replace function public.activate_caterer_subscription(
    p_checkout_session_id text,
    p_payment_id text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
    subscription_row public.caterer_subscriptions%rowtype;
    renewal_start timestamptz;
    renewal_end timestamptz;
begin
    select * into subscription_row
    from public.caterer_subscriptions
    where paymongo_checkout_session_id = p_checkout_session_id
    for update;

    if not found then
        raise exception 'Subscription checkout not found';
    end if;

    if subscription_row.status = 'active' then
        if subscription_row.paymongo_payment_id is null and p_payment_id is not null then
            update public.caterer_subscriptions
            set paymongo_payment_id = p_payment_id
            where id = subscription_row.id;
            return;
        end if;
        if p_payment_id is null or subscription_row.paymongo_payment_id = p_payment_id then
            return;
        end if;
        raise exception 'Subscription has already been activated by a different payment';
    end if;

    if subscription_row.status <> 'pending' then
        raise exception 'Subscription is not pending';
    end if;

    perform 1
    from public.caterers
    where id = subscription_row.caterer_id
    for update;

    select greatest(coalesce(max(expires_at), now()), now())
    into renewal_start
    from public.caterer_subscriptions
    where caterer_id = subscription_row.caterer_id
      and status = 'active'
      and expires_at > now();

    renewal_end := case subscription_row.plan
        when 'monthly' then renewal_start + interval '1 month'
        when 'yearly' then renewal_start + interval '1 year'
    end;

    update public.caterer_subscriptions
    set status = 'active',
        paymongo_payment_id = p_payment_id,
        started_at = renewal_start,
        expires_at = renewal_end,
        updated_at = now()
    where id = subscription_row.id;
end;
$$;

revoke all on function public.activate_caterer_subscription(text, text) from public, anon, authenticated;
grant execute on function public.activate_caterer_subscription(text, text) to service_role;

create or replace function public.caterer_has_active_subscription_for_auth_user()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select exists (
        select 1
        from public.caterer_subscriptions s
        join public.caterers c on c.id = s.caterer_id
        join public.users u on u.id = c.user_id
        where u.auth_user_id = auth.uid()
          and c.is_suspended = false
          and s.status = 'active'
          and s.expires_at > now()
    );
$$;

revoke all on function public.caterer_has_active_subscription_for_auth_user() from public, anon;
grant execute on function public.caterer_has_active_subscription_for_auth_user() to authenticated;

drop policy if exists packages_owner_insert on public.packages;
create policy packages_owner_insert on public.packages
for insert to authenticated
with check (
    caterer_id = (select caterer_id from public.get_my_profile())
    and public.caterer_has_active_subscription_for_auth_user()
    and not exists (
        select 1 from public.caterers c
        where c.id = packages.caterer_id and c.is_suspended
    )
);

